#!/usr/bin/env python3
"""Render the Tier-1 and Tier-2 agent files from the shared annotation spec.

Both agents must follow one spec, and a subagent never sees another agent's
system prompt, so the full spec is inlined into each agent file. Edit
prompts/endophora_spec.md (or the tier text below), then run this script.
`--check` exits non-zero if the agent files are stale; run_pipeline.py runs
that check before starting.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

ROOT_DIR = pathlib.Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT_DIR / "prompts" / "endophora_spec.md"
AGENTS_DIR = ROOT_DIR / ".claude" / "agents"

GENERATED_NOTE = (
    "<!-- Generated by src/build_agents.py from prompts/endophora_spec.md. "
    "Edit those, then rerun the script; do not edit this file. -->"
)

TIER2_PREAMBLE = """\
# Tier-2 Adjudication

You are the Tier-2 adjudicator for the MTG Endophora Dataset. You receive a card that the Tier-1 annotator could not settle: either it returned `verdict: "uncertain"`, or its output failed the automatic grounding checks. The Tier-1 output and the reason for escalation (its `uncertainty_reason` and/or the list of grounding errors) follow the card text.

- Re-annotate the whole card from scratch under the specification below. Do not copy Tier-1 mentions without checking them.
- Fix every listed grounding error: spans must be verbatim substrings of the named ability, and occurrence indices must be correct.
- When a resolution depends on the Comprehensive Rules (e.g. CR 607 linked abilities, CR 608.2c/h resolving spells and abilities, CR 603 triggered abilities, CR 614 replacement effects), use the `mtg-rules` lookup scripts. The escalation message names their directory. Run them by absolute path (`<dir>/scripts/rule 607.2a`, `<dir>/scripts/rulings <card>`, `<dir>/scripts/define <term>`), with no `cd` or pipes: only those scripts are permitted, and any other shell command is refused. Read `<dir>/SKILL.md` only if you need usage details beyond that. Cite the rule in `uncertainty_reason` only if the verdict stays `"uncertain"`.
- If you can resolve the uncertainty, set `verdict: "ok"` and `uncertainty_reason: null`. If the text is genuinely ambiguous even under the CR, keep `verdict: "uncertain"` and explain the exact CR or linguistic defect.

The full specification follows; it is identical to the one Tier-1 uses.

---

"""

AGENTS = {
    "endophora-haiku": {
        "frontmatter": {
            "name": "endophora-haiku",
            "description": "Tier-1 annotator that maps endophoric mentions in preprocessed MTG Oracle text to their antecedents.",
            # StructuredOutput is how `claude -p --json-schema` returns its result;
            # an agent tool list that omits it silently disables structured output.
            "tools": "StructuredOutput",
            "model": "haiku",
        },
        "preamble": "",
    },
    "endophora-opus": {
        "frontmatter": {
            "name": "endophora-opus",
            "description": "Tier-2 linguistic and MTG rules adjudicator for resolving uncertain endophoric mentions on complex Magic cards.",
            "tools": "Read, Bash, StructuredOutput",
            "model": "opus",
        },
        "preamble": TIER2_PREAMBLE,
    },
}


def spec_sha() -> str:
    """Short hash of the spec, recorded on every output row."""
    return hashlib.sha256(SPEC_PATH.read_bytes()).hexdigest()[:12]


def render(agent: str) -> str:
    cfg = AGENTS[agent]
    fm = "\n".join(f"{k}: {v}" for k, v in cfg["frontmatter"].items())
    spec = SPEC_PATH.read_text(encoding="utf-8").strip()
    return f"---\n{fm}\n---\n{GENERATED_NOTE}\n\n{cfg['preamble']}{spec}\n"


def stale_agents() -> list[str]:
    stale = []
    for agent in AGENTS:
        path = AGENTS_DIR / f"{agent}.md"
        if not path.exists() or path.read_text(encoding="utf-8") != render(agent):
            stale.append(agent)
    return stale


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Exit 1 if agent files are stale")
    args = parser.parse_args()

    if args.check:
        stale = stale_agents()
        if stale:
            print(f"Stale agent files: {', '.join(stale)}. Run src/build_agents.py.", file=sys.stderr)
            sys.exit(1)
        return

    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    for agent in AGENTS:
        (AGENTS_DIR / f"{agent}.md").write_text(render(agent), encoding="utf-8")
        print(f"wrote .claude/agents/{agent}.md (spec {spec_sha()})")


if __name__ == "__main__":
    main()
